#!/usr/bin/env python3
"""Write pixelpane/static/led5x7.js: the board's own 5x7 font as rows of lit dots, so the
web pages can draw a title exactly the way the panel does. Rerun after changing the font."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
glyphs, code, rows, in_bitmap = {}, None, [], False
for line in (ROOT / "pixelpane/fonts/5x7.bdf").read_text().splitlines():
    if line.startswith("ENCODING"):
        code = int(line.split()[1])
    elif line == "BITMAP":
        in_bitmap, rows = True, []
    elif line == "ENDCHAR":
        if code is not None and 32 <= code <= 126:
            glyphs[chr(code)] = "".join(format(int(r, 16), "08b")[:5] for r in rows)   # 7 rows x 5 columns
        in_bitmap = False
    elif in_bitmap:
        rows.append(line)
body = ",".join(f"{repr(c) if c != chr(39) else chr(34) + c + chr(34)}:'{bits}'" for c, bits in sorted(glyphs.items()))
(ROOT / "pixelpane/static/led5x7.js").write_text(
    "// Generated by tools/make-led-font.py from pixelpane/fonts/5x7.bdf: each glyph is 7 rows of 5 dots, '1' lit.\n"
    f"const LED_FONT = {{{body}}};\n")
print(len(glyphs), "glyphs")
